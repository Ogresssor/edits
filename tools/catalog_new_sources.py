def preview(c):
    if c['grade']!='strong':return
    dest=OUT/c['preview'];dest.parent.mkdir(exist_ok=True)
    receipt=dest.with_suffix('.check.json')
    if dest.exists() and receipt.exists():return
    ffmpeg.run(['-ss',str(c['start']),'-i',c['source'],'-t',str(c['end']-c['start']),
        '-map','0:v:0','-map',c['audio_map'],'-vf','scale=640:-2','-c:v','libx264','-threads','2',
        '-preset','veryfast','-crf','27','-c:a','aac','-b:a','96k','-ac','2','-movflags','+faststart',str(dest)],timeout=240)
    info=ffmpeg.probe(dest)
    assert info.width==640 and info.has_audio and abs(info.duration-(c['end']-c['start']))<.3
    ffmpeg.run(['-i',str(dest),'-f','null','-'],timeout=90)
    ingest.save(receipt,dict(source=c['source'],start=c['start'],end=c['end'],duration=info.duration,
                full_decode=True,has_audio=True,bytes=dest.stat().st_size,stage='context_preview_not_final_short'))
    print('PREVIEW',c['id'],round(info.duration,1),flush=True)


