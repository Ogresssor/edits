"""Deterministic caption design; plain user text never becomes ASS code."""
PROFILES = {
    'clean': dict(size=70, primary='&H00FFFFFF', outline=2.5, italic=0),
    'accent': dict(size=74, primary='&H00FFFFFF', outline=2.5, italic=-1),
    'cinema': dict(size=54, primary='&H00EAEAEA', outline=2, italic=0),
    'intrigue': dict(size=60, primary='&H00FFFFFF', outline=2.5, italic=0),
}
VERSION = 'caption-design-2026-11-15.2'


def ass_time(value):
    centiseconds = round(value * 100)
    return f'{centiseconds//360000}:{centiseconds//6000%60:02}:{centiseconds//100%60:02}.{centiseconds%100:02}'


def plain(value, limit=100):
    if (not isinstance(value, str) or not value.strip() or len(value) > limit
            or any(c in value for c in ('{', '}', '\\', '\n', '\r'))):
        raise ValueError('Use plain text without ASS commands or newlines')
    return value


def caption_text(caption, profile, scale):
    text = plain(caption['text'])
    highlight = caption.get('highlight')
    if not highlight:
        return text.upper() if profile == 'accent' else text
    plain(highlight)
    if text.count(highlight) != 1:
        raise ValueError('Highlight must occur exactly once inside the caption')
    before, after = text.split(highlight)
    if profile == 'accent':
        # Larger punch line on its own line, generated by the renderer only.
        prefix = before.strip().upper()
        return ((prefix + r'\N') if prefix else '') + (
            r'{\c&H6BE8C6&\fs' + str(round(96*scale)) + r'}' + highlight.upper()
            + r'{\rDefault}' + after.upper())
    return before + r'{\c&H84DFF4&}' + highlight + r'{\rDefault}' + after


def captions(plan, profile, width, height):
    style = PROFILES[profile]; scale = width / 1080
    # Explicit safe rectangle: x=90..900, y starts at 61% of the canvas.
    left, right, y = round(90*scale), round(180*scale), round(height*.61)
    header = (f'[Script Info]\nScriptType: v4.00+\nPlayResX: {width}\nPlayResY: {height}\nWrapStyle: 0\nScaledBorderAndShadow: yes\n'
              '[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n'
              f"Style: Default,Montserrat,{round(style['size']*scale)},{style['primary']},&H00FFFFFF,&H00202020,&H80000000,-1,{style['italic']},0,0,100,100,0,0,1,{style['outline']*scale},0,8,{left},{right},{y},1\n"
              f'Style: Hook,Montserrat,{round(40*scale)},&H00151515,&H00151515,&H00FFFFFF,&H00FFFFFF,-1,0,0,0,100,100,0,0,3,{round(12*scale)},0,8,{left},{right},{round(height*.12)},1\n'
              f'Style: Demo,Montserrat,{round(25*scale)},&H00FFFFFF,&H00FFFFFF,&H00202020,&H80000000,0,0,0,0,100,100,0,0,1,{scale},0,8,{left},{right},{round(height*.06)},1\n'
              '[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n')
    events = []
    for c in plan.get('captions', []):
        content = caption_text(c, profile, scale)
        # Brief entrance, not incessant word-by-word jumping or looping animation.
        content = r'{\fad(55,55)}' + content
        events.append(f"Dialogue: 1,{ass_time(c['start'])},{ass_time(c['end'])},Default,,0,0,0,,{content}\n")
    duration = sum(s['end']-s['start'] for s in plan['segments'])
    if profile == 'intrigue' and plan.get('on_screen_hook'):
        hook = plain(plan['on_screen_hook'], 55)
        events.append(f'Dialogue: 2,0:00:00.00,{ass_time(min(2.4,duration))},Hook,,0,0,0,,{hook}\n')
    if plan.get('demonstration'):
        events.append(f'Dialogue: 3,0:00:00.00,{ass_time(duration)},Demo,,0,0,0,,ДЕМОНСТРАЦИЯ ОФОРМЛЕНИЯ\n')
    return header + ''.join(events)
